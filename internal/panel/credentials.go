// credentialJSON is the API representation of a credential. It deliberately
// omits password_hash entirely (models carry the hash internally only).
type credentialJSON struct {
	ID               string     `json:"id"`
	Username         string     `json:"username"`
	Groups           []string   `json:"groups,omitempty"`
	Enabled          bool       `json:"enabled"`
	ExpiresAt        *time.Time `json:"expires_at,omitempty"`
	MaxConcurrent    int        `json:"max_concurrent"`
	BandwidthKbps    int        `json:"bandwidth_kbps"`
	AllowedProtocols []string   `json:"allowed_protocols,omitempty"`
	SourceCIDRs      []string   `json:"source_cidrs,omitempty"`
	Note             string     `json:"note,omitempty"`
	LastUsedAt       *time.Time `json:"last_used_at,omitempty"`
	BytesIn          uint64     `json:"bytes_in"`
	BytesOut         uint64     `json:"bytes_out"`
	CreatedAt        time.Time  `json:"created_at"`
	UpdatedAt        time.Time  `json:"updated_at"`
}

// newCredentialJSON converts a model credential (hash always cleared).
func newCredentialJSON(cred model.Credential) credentialJSON {
	redacted := cred.Redacted()
	return credentialJSON{
		ID:               redacted.ID,
		Username:         redacted.Username,
		Groups:           redacted.Groups,
		Enabled:          redacted.Enabled,
		ExpiresAt:        redacted.ExpiresAt,
		MaxConcurrent:    redacted.MaxConcurrent,
		BandwidthKbps:    redacted.BandwidthKbps,
		AllowedProtocols: redacted.AllowedProtocols,
		SourceCIDRs:      redacted.SourceCIDRs,
		Note:             redacted.Note,
		LastUsedAt:       redacted.LastUsedAt,
		BytesIn:          redacted.BytesIn,
		BytesOut:         redacted.BytesOut,
		CreatedAt:        redacted.CreatedAt,
		UpdatedAt:        redacted.UpdatedAt,
	}
}

// credentialsListResponse is the GET /api/v1/credentials payload.
type credentialsListResponse struct {
	Items []credentialJSON `json:"items"`
}

// credentialWriteResponse is returned by create/update. The plain password is
// returned exactly once and only when it was generated by the server.
type credentialWriteResponse struct {
	Credential credentialJSON `json:"credential"`
	Password   string         `json:"password,omitempty"`
}

// optionalTime distinguishes an absent JSON field from an explicit null so the
// expiry can be cleared as well as set.
type optionalTime struct {
	Set   bool
	Value *time.Time
}

// UnmarshalJSON implements json.Unmarshaler.
func (o *optionalTime) UnmarshalJSON(data []byte) error {
	o.Set = true
	if string(data) == "null" {
		o.Value = nil
		return nil
	}
	var parsed time.Time
	if err := json.Unmarshal(data, &parsed); err != nil {
		return err
	}
	utc := parsed.UTC()
	o.Value = &utc
	return nil
}

// credentialRequest is the create/update body for proxy credentials.
type credentialRequest struct {
	Username         *string      `json:"username"`
	Password         *string      `json:"password"`
	GeneratePassword *bool        `json:"generate_password"`
	Groups           *[]string    `json:"groups"`
	Enabled          *bool        `json:"enabled"`
	ExpiresAt        optionalTime `json:"expires_at"`
	MaxConcurrent    *int         `json:"max_concurrent"`
	BandwidthKbps    *int         `json:"bandwidth_kbps"`
	AllowedProtocols *[]string    `json:"allowed_protocols"`
	SourceCIDRs      *[]string    `json:"source_cidrs"`
	Note             *string      `json:"note"`
}

// handleCredentialsList serves GET /api/v1/credentials.
func (s *Server) handleCredentialsList(w http.ResponseWriter, r *http.Request) {
	stored := s.opts.Auth.List()
	items := make([]credentialJSON, 0, len(stored))
	for _, cred := range stored {
		items = append(items, newCredentialJSON(cred))
	}
	s.writeJSON(w, http.StatusOK, credentialsListResponse{Items: items})
}

// handleCredentialCreate serves POST /api/v1/credentials.
func (s *Server) handleCredentialCreate(w http.ResponseWriter, r *http.Request) {
	var req credentialRequest
	if !s.readJSON(w, r, &req, true, false) {
		return
	}
	username := stringValue(req.Username)
	if username == "" {
		s.writeValidationError(w, "用户名不能为空", fieldError{Field: "username", Message: "不能为空"})
		return
	}
	password, hash, generated, err := s.resolvePassword(req.Password, req.GeneratePassword)
	if err != nil {
		s.writeValidationError(w, err.Error(), fieldError{Field: "password", Message: err.Error()})
		return
	}
	cred := model.Credential{
		Username:     username,
		PasswordHash: hash,
		Enabled:      true,
	}
	if req.Enabled != nil {
		cred.Enabled = *req.Enabled
	}
	applyCredentialFields(&cred, &req)
	if req.ExpiresAt.Set {
		cred.ExpiresAt = req.ExpiresAt.Value
	}

	created, err := s.opts.Auth.Create(cred)
	if err != nil {
		s.writeCredentialStoreError(w, err)
		return
	}
	resp := credentialWriteResponse{Credential: newCredentialJSON(created)}
	if generated {
		resp.Password = password
	}
	s.auditRequest(r, "credential.create", created.ID, "ok", map[string]string{
		"username": created.Username,
		"groups":   strings.Join(created.Groups, ","),
	})
	s.log.Info("代理凭据已创建", "credential_id", created.ID, "username", created.Username,
		"generated_password", generated, "actor", sessionUsername(r))
	s.notify()
	s.writeJSON(w, http.StatusOK, resp)
}

// handleCredentialUpdate serves PATCH /api/v1/credentials/{id}.
func (s *Server) handleCredentialUpdate(w http.ResponseWriter, r *http.Request) {
	credID := strings.TrimSpace(r.PathValue("id"))
	existing, ok := s.opts.Auth.Get(credID)
	if !ok {
		s.writeError(w, http.StatusNotFound, "not_found", "代理凭据不存在", nil)
		return
	}
	var req credentialRequest
	if !s.readJSON(w, r, &req, true, false) {
		return
	}
	next := existing
	if req.Username != nil {
		next.Username = strings.TrimSpace(*req.Username)
	}
	if req.Enabled != nil {
		next.Enabled = *req.Enabled
	}
	applyCredentialFields(&next, &req)
	if req.ExpiresAt.Set {
		next.ExpiresAt = req.ExpiresAt.Value
	}

	generated := false
	password := ""
	if needsPasswordChange(req.Password, req.GeneratePassword) {
		resolved, hash, wasGenerated, err := s.resolvePassword(req.Password, req.GeneratePassword)
		if err != nil {
			s.writeValidationError(w, err.Error(), fieldError{Field: "password", Message: err.Error()})
			return
		}
		next.PasswordHash = hash
		generated = wasGenerated
		password = resolved
	}

	updated, err := s.opts.Auth.Update(next)
	if err != nil {
		s.writeCredentialStoreError(w, err)
		return
	}
	resp := credentialWriteResponse{Credential: newCredentialJSON(updated)}
	if generated {
		resp.Password = password
	}
	s.auditRequest(r, "credential.update", credID, "ok", map[string]string{
		"username":         updated.Username,
		"password_changed": boolText(needsPasswordChange(req.Password, req.GeneratePassword)),
	})
	s.log.Info("代理凭据已更新", "credential_id", credID, "username", updated.Username,
		"password_changed", needsPasswordChange(req.Password, req.GeneratePassword),
		"actor", sessionUsername(r))
	s.notify()
	s.writeJSON(w, http.StatusOK, resp)
}

// applyCredentialFields copies the optional list/limit fields onto dest.
func applyCredentialFields(dest *model.Credential, req *credentialRequest) {
	if req.Groups != nil {
		dest.Groups = *req.Groups
	}
	if req.MaxConcurrent != nil {
		dest.MaxConcurrent = *req.MaxConcurrent
	}
	if req.BandwidthKbps != nil {
		dest.BandwidthKbps = *req.BandwidthKbps
	}
	if req.AllowedProtocols != nil {
		dest.AllowedProtocols = *req.AllowedProtocols
	}
	if req.SourceCIDRs != nil {
		dest.SourceCIDRs = *req.SourceCIDRs
	}
	if req.Note != nil {
		dest.Note = strings.TrimSpace(*req.Note)
	}
}

// needsPasswordChange reports whether a request asks for a new password.
func needsPasswordChange(password *string, generate *bool) bool {
	if generate != nil && *generate {
		return true
	}
	return password != nil && strings.TrimSpace(*password) != ""
}

// resolvePassword decides whether to generate or hash the requested password.
// When neither a password nor generate_password is supplied the panel generates
// a random password (the panel UI documents "留空 = 由服务端生成"); the plain
// value is then returned to the caller exactly once.
func (s *Server) resolvePassword(password *string, generate *bool) (plain, hash string, generated bool, err error) {
	explicit := password != nil && strings.TrimSpace(*password) != ""
	if (generate != nil && *generate) || !explicit {
		plain, err = auth.GeneratePassword(24)
		if err != nil {
			return "", "", false, fmt.Errorf("生成随机密码失败")
		}
		generated = true
	} else {
		// Never trim the password itself: leading/trailing spaces are valid
		// characters and must hash exactly as the operator typed them.
		plain = *password
	}
	if len(plain) < 8 {
		return "", "", false, errors.New("密码至少 8 个字符")
	}
	hash, err = auth.HashPassword(plain)
	if err != nil {
		return "", "", false, errors.New("密码不符合要求（最多 1024 字节）")
	}
	return plain, hash, generated, nil
}

// handleCredentialDelete serves DELETE /api/v1/credentials/{id}.
func (s *Server) handleCredentialDelete(w http.ResponseWriter, r *http.Request) {
	credID := strings.TrimSpace(r.PathValue("id"))
	cred, ok := s.opts.Auth.Get(credID)
	if !ok {
		s.writeError(w, http.StatusNotFound, "not_found", "代理凭据不存在", nil)
		return
	}
	if err := s.opts.Auth.Delete(credID); err != nil {
		s.writeInternalError(w, err, "删除代理凭据失败")
		return
	}
	kicked := s.kickCredential(credID)
	s.auditRequest(r, "credential.delete", credID, "ok", map[string]string{
		"username":        cred.Username,
		"kicked_sessions": itoa(kicked),
	})
	s.log.Info("代理凭据已删除", "credential_id", credID, "username", cred.Username,
		"kicked_sessions", kicked, "actor", sessionUsername(r))
	s.notify()
	s.writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
}

// kickCredentialSessionsResponse is the kick-sessions payload.
type kickCredentialSessionsResponse struct {
	Kicked int `json:"kicked"`
}

// handleCredentialKickSessions serves POST /credentials/{id}/kick-sessions.
func (s *Server) handleCredentialKickSessions(w http.ResponseWriter, r *http.Request) {
	credID := strings.TrimSpace(r.PathValue("id"))
	cred, ok := s.opts.Auth.Get(credID)
	if !ok {
		s.writeError(w, http.StatusNotFound, "not_found", "代理凭据不存在", nil)
		return
	}
	kicked := s.kickCredential(credID)
	s.auditRequest(r, "credential.kick_sessions", credID, "ok", map[string]string{
		"username": cred.Username,
		"kicked":   itoa(kicked),
	})
	s.log.Warn("已踢掉凭据的全部会话", "credential_id", credID, "username", cred.Username,
		"kicked", kicked, "actor", sessionUsername(r))
	s.notify()
	s.writeJSON(w, http.StatusOK, kickCredentialSessionsResponse{Kicked: kicked})
}

// kickCredential closes the live sessions of one credential (when wired).
func (s *Server) kickCredential(credentialID string) int {
	if s.opts.KickCredential == nil {
		return 0
	}
	return s.opts.KickCredential(credentialID)
}

// credentialUsageResponse is the GET /credentials/{id}/usage payload.
type credentialUsageResponse struct {
	LastUsedAt        *time.Time `json:"last_used_at,omitempty"`
	BytesIn           uint64     `json:"bytes_in"`
	BytesOut          uint64     `json:"bytes_out"`
	ActiveConnections int64      `json:"active_connections"`
}

// handleCredentialUsage serves GET /credentials/{id}/usage. Active connections
// come from the app's in-flight counter; the store supplies the persistent
// usage counters.
func (s *Server) handleCredentialUsage(w http.ResponseWriter, r *http.Request) {
	credID := strings.TrimSpace(r.PathValue("id"))
	cred, ok := s.opts.Auth.Get(credID)
	if !ok {
		s.writeError(w, http.StatusNotFound, "not_found", "代理凭据不存在", nil)
		return
	}
	var active int64
	if s.opts.ActiveCredentialSessions != nil {
		active = s.opts.ActiveCredentialSessions(credID)
	}
	s.writeJSON(w, http.StatusOK, credentialUsageResponse{
		LastUsedAt:        cred.LastUsedAt,
		BytesIn:           cred.BytesIn,
		BytesOut:          cred.BytesOut,
		ActiveConnections: active,
	})
}

// visibleNodesResponse is shared by /credentials/{id}/visible-nodes and the
// panel group page.
type visibleNodesResponse struct {
	Count int          `json:"count"`
	Nodes []model.Node `json:"nodes"`
}

// handleCredentialVisibleNodes serves GET /credentials/{id}/visible-nodes: the
// nodes the credential can currently be scheduled on.
func (s *Server) handleCredentialVisibleNodes(w http.ResponseWriter, r *http.Request) {
	credID := strings.TrimSpace(r.PathValue("id"))
	cred, ok := s.opts.Auth.Get(credID)
	if !ok {
		s.writeError(w, http.StatusNotFound, "not_found", "代理凭据不存在", nil)
		return
	}
	nodeList := s.opts.Registry.List()
	pointerList := make([]*model.Node, len(nodeList))
	for i := range nodeList {
		pointerList[i] = &nodeList[i]
	}
	candidates := s.opts.Groups.Candidates(cred.Groups, pointerList)
	nodes := make([]model.Node, 0, len(candidates))
	for _, node := range candidates {
		if node == nil {
			continue
		}
		nodes = append(nodes, *node)
	}
	sortNodes(nodes)
	s.writeJSON(w, http.StatusOK, visibleNodesResponse{Count: len(nodes), Nodes: nodes})
}

// writeCredentialStoreError maps credential store errors to 409/422 responses.
func (s *Server) writeCredentialStoreError(w http.ResponseWriter, err error) {
	message := err.Error()
	switch {
	case strings.Contains(message, "已存在"):
		s.writeError(w, http.StatusConflict, "conflict", message, nil)
	case strings.Contains(message, "不存在"):
		s.writeError(w, http.StatusNotFound, "not_found", message, nil)
	default:
		s.writeValidationError(w, "凭据数据校验失败", parseStoreFieldError(err, "credential"))
	}
}

// boolText renders a bool as "true"/"false" for audit details.
func boolText(v bool) string {
	if v {
		return "true"
	}
	return "false"
}
